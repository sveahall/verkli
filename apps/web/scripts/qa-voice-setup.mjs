import { chromium, expect as baseExpect } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
const expect = baseExpect.configure({ timeout: 15000 });
const base = new URL(process.env.VOICE_SETUP_QA_URL || "http://127.0.0.1:3248");
if (!["localhost", "127.0.0.1"].includes(base.hostname)) throw new Error("Voice setup QA is local-only");
const output = process.env.VOICE_SETUP_QA_OUTPUT || "/tmp/verkli-voice-setup-qa";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 1400, height: 1050 } });
page.setDefaultTimeout(20000);
const checks = [], errors = [];
page.on("pageerror", (error) => errors.push(error.message));
const create = page.getByRole("button", { name: "Create synthetic voice", exact: true });
const consent = page.getByRole("checkbox", { name: "I consent to this synthetic demo operation.", exact: true });
const status = page.getByRole("status").filter({ hasText: /operation|Requesting|Ready|Failed|Uncertain|Deleting|Deleted/ });
const hasStatus = async (prefix) => expect(status).toContainText(prefix);
async function fresh(mode = "success") {
  await page.evaluate(() => sessionStorage.removeItem("verkli-voice-studio-v1"));
  await page.reload(); await expect(create).toBeVisible();
  await page.getByRole("combobox", { name: "Worker scenario", exact: true }).selectOption(mode);
}
async function start() { await consent.check(); await create.click(); }
try {
  await writeFile(path.join(output, "result.json"), JSON.stringify({ status: "RUNNING", startedAt: new Date().toISOString() }));
  await page.goto(new URL("/dev/voice-setup", base).href, { timeout: 90000 });
  await expect(create).toBeDisabled();
  await page.getByRole("combobox", { name: "Synthetic sample", exact: true }).selectOption("missing");
  await consent.check(); await expect(create).toBeDisabled();
  await page.getByRole("combobox", { name: "Synthetic sample", exact: true }).selectOption("synthetic-invalid"); await expect(create).toBeDisabled();
  await page.getByRole("combobox", { name: "Synthetic sample", exact: true }).selectOption("synthetic-valid");
  await consent.uncheck(); await consent.focus(); await page.keyboard.press("Space"); await expect(consent).toBeChecked();
  await expect(create).toBeEnabled(); checks.push("explicit consent, valid synthetic sample and keyboard checkbox required");
  await create.evaluate((button) => { button.click(); button.click(); });
  await hasStatus("Ready"); await expect(page.getByLabel("Synthetic creates", { exact: true })).toHaveText("1");
  await page.reload(); await hasStatus("Ready"); await expect(consent).toBeChecked();
  await expect(page.getByLabel("Synthetic creates", { exact: true })).toHaveText("1");
  const cookie = page.getByRole("button", { name: "Essential only", exact: true }); if (await cookie.isVisible()) await cookie.click();
  await page.screenshot({ path: path.join(output, "desktop.png"), fullPage: true });
  checks.push("double click dispatches once; verified ready and recorded consent survive reload");
  await page.getByRole("button", { name: "Revoke demo consent", exact: true }).click(); await hasStatus("Deleted");
  await page.getByRole("button", { name: "Restart simulated worker", exact: true }).click(); await hasStatus("Deleted");
  await expect(page.getByLabel("Synthetic deletes", { exact: true })).toHaveText("1"); checks.push("completed deletion survives restart without another delete");
  await fresh("uncertain"); await start(); await hasStatus("Uncertain"); await expect(create).toHaveCount(0);
  await page.getByRole("button", { name: "Reconcile original request", exact: true }).click(); await hasStatus("Ready");
  await expect(page.getByLabel("Synthetic creates", { exact: true })).toHaveText("1"); checks.push("uncertain outcome reconciles original operation without another create");
  await fresh(); await start();
  await page.evaluate(() => { window.voiceReadySeen = false; window.voiceObserver = new MutationObserver(() => { if ([...document.querySelectorAll('[role="status"]')].some((node) => node.textContent.startsWith("Ready"))) window.voiceReadySeen = true; }); window.voiceObserver.observe(document.body, { childList: true, subtree: true, characterData: true }); });
  await page.getByRole("button", { name: "Revoke demo consent", exact: true }).click(); await hasStatus("Deleted");
  assert.equal(await page.evaluate(() => { window.voiceObserver.disconnect(); return window.voiceReadySeen; }), false);
  await expect(page.getByLabel("Synthetic deletes", { exact: true })).toHaveText("1"); checks.push("revocation before late success never displays ready and cleans original voice");
  await fresh("cleanup-error"); await start(); await hasStatus("Ready");
  const operation = await page.locator("dd").first().textContent();
  await page.getByRole("button", { name: "Revoke demo consent", exact: true }).click();
  await expect(page.locator("main").getByRole("alert")).toContainText("Synthetic deletion failed");
  await page.reload(); await hasStatus("Deleting"); await expect(page.locator("dd").first()).toHaveText(operation);
  await page.getByRole("button", { name: "Retry cleanup", exact: true }).click(); await hasStatus("Deleted");
  await expect(page.getByLabel("Synthetic creates", { exact: true })).toHaveText("1");
  await expect(page.getByLabel("Synthetic deletes", { exact: true })).toHaveText("1"); checks.push("failed cleanup resumes same operation after actual page reload");
  await fresh(); await start();
  await page.getByRole("combobox", { name: "Demo author", exact: true }).selectOption("demo-author-b");
  await expect(create).toBeVisible(); await expect(page.locator("dd")).toHaveCount(0); await expect(consent).not.toBeChecked();
  await start(); await hasStatus("Ready"); await expect(page.locator("dd").nth(1)).toHaveText("demo-author-b");
  await page.getByRole("combobox", { name: "Demo author", exact: true }).selectOption("demo-author-a"); await hasStatus("Ready");
  await expect(page.locator("dd").nth(1)).toHaveText("demo-author-a");
  await expect(page.getByLabel("Synthetic creates", { exact: true })).toHaveText("2"); checks.push("author switching isolates in-flight and completed operations");
  await fresh("failure"); await start(); await hasStatus("Failed"); await expect(create).toHaveCount(0); checks.push("confirmed failure has no ready voice or automatic create retry");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, "mobile.png"), fullPage: true }); checks.push("390px viewport without overflow");
  await fresh(); await start(); await hasStatus("Ready");
  await page.evaluate(() => { const original = Storage.prototype.setItem; Storage.prototype.setItem = function (key, value) { if (key === "verkli-voice-studio-v1") throw new Error("Synthetic browser storage failure"); return original.call(this, key, value); }; });
  await page.getByRole("button", { name: "Revoke demo consent", exact: true }).click();
  await hasStatus("Setup is locked"); await expect(create).toBeDisabled();
  await expect(page.getByRole("button", { name: "Revoke demo consent", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Retry loading operation", exact: true }).click(); await hasStatus("Setup is locked");
  await page.reload(); await hasStatus("Ready");
  await page.getByRole("button", { name: "Revoke demo consent", exact: true }).click(); await hasStatus("Deleted");
  checks.push("failed revocation save removes stale ready, locks actions and recovers from persisted state");
  await page.evaluate(() => sessionStorage.setItem("verkli-voice-studio-v1", '{"invalid":true}')); await page.reload();
  await expect(page.locator("main").getByRole("alert")).toBeVisible(); await expect(create).toHaveCount(0); checks.push("invalid persisted state fails closed");
  assert.deepEqual(errors, []);
  await fresh();
  await writeFile(path.join(output, "result.json"), JSON.stringify({ status: "PASS", checks, browser: browser.version(), syntheticOnly: true }, null, 2));
  console.log(`PASS ${checks.length} voice studio browser checks`);
} catch (error) {
  await writeFile(path.join(output, "result.json"), JSON.stringify({ status: "FAIL", checks, errors, error: String(error) }, null, 2));
  await page.screenshot({ path: path.join(output, "failure.png"), fullPage: true, timeout: 5000 }).catch(() => {}); throw error;
} finally { await browser.close(); }
