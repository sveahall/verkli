import { chromium, expect as baseExpect } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
const expect = baseExpect.configure({ timeout: 15000 });
const base = new URL(process.env.PRONUNCIATION_QA_URL || "http://localhost:3215");
if (!["localhost", "127.0.0.1"].includes(base.hostname)) throw new Error("Pronunciation QA is local-only");
const output = process.env.PRONUNCIATION_QA_OUTPUT || "/tmp/verkli-pronunciation-recovery";
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
page.setDefaultTimeout(30_000);
const errors = [], checks = [];
page.on("pageerror", (error) => errors.push(error.message));
const written = page.getByRole("textbox", { name: "Written form 1", exact: true });
const spoken = page.getByRole("textbox", { name: "Spoken as 1", exact: true });
const mode = page.getByLabel("Simulated response");
const save = page.getByRole("button", { name: "Save in demo", exact: true });
const latest = page.getByRole("button", { name: "Load latest and replace draft", exact: true });
try {
  await writeFile(path.join(output, "result.json"), JSON.stringify({ status: "RUNNING", startedAt: new Date().toISOString() }));
  await page.goto(new URL("/dev/pronunciation", base).href, { timeout: 90_000 });
  await expect(page.getByText("No saved rules for this edition", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add a pronunciation rule" }).click();
  await written.fill("Mira"); await spoken.fill("Retained draft");
  await mode.selectOption("conflict"); await save.click(); await expect(latest).toBeVisible();
  await mode.selectOption("load-error"); await latest.click();
  await expect(page.getByText("Rules could not be loaded. Please retry before editing.", { exact: true })).toBeVisible();
  await expect(written).toHaveValue("Mira"); await expect(spoken).toHaveValue("Retained draft");
  await expect(written).toBeDisabled(); await expect(spoken).toBeDisabled(); await expect(save).toBeDisabled();
  await expect(page.getByRole("button", { name: "Remove rule 1" })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Add a pronunciation rule" })).toBeDisabled();
  const retry = page.getByRole("button", { name: "Retry loading rules", exact: true });
  await expect(retry).toBeVisible();
  checks.push("failed conflict recovery retains draft, disables editing/save and offers retry");
  await retry.click(); await expect(retry).toBeEnabled(); await expect(written).toBeDisabled();
  checks.push("repeated load failure does not release recovery lock");
  await mode.selectOption("normal"); await retry.click();
  await expect(written).toHaveValue("Bay"); await expect(spoken).toHaveValue("Bey"); await expect(written).toBeEnabled();
  await spoken.fill("New draft"); await expect(save).toBeEnabled();
  checks.push("successful current-scope retry replaces draft and restores editing");
  await mode.selectOption("conflict"); await save.click(); await expect(latest).toBeVisible();
  await mode.selectOption("delayed"); await latest.click();
  await mode.selectOption("normal"); await page.getByLabel("Demo author").selectOption("author-two");
  await page.getByLabel("Edition", { exact: true }).selectOption("sv");
  await expect(page.getByText("No saved rules for this edition", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add a pronunciation rule" }).click();
  await written.fill("Mira"); await spoken.fill("New owner draft");
  // The fixture's delayed read resolves after1800ms. Assert again after that response.
  await page.waitForTimeout(2000);
  await expect(spoken).toHaveValue("New owner draft"); await expect(save).toBeEnabled(); await expect(latest).toHaveCount(0);
  checks.push("late recovery read cannot overwrite a new owner and edition");
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, "result.json"), JSON.stringify({ status: "PASS", checks, fixtureOnly: true, browser: browser.version() }, null, 2));
  console.log(`PASS ${checks.length} recovery checks`);
} catch (error) {
  await writeFile(path.join(output, "result.json"), JSON.stringify({ status: "FAIL", checks, errors, error: String(error) }, null, 2));
  await page.screenshot({ path: path.join(output, "failure.png"), fullPage: true, timeout: 5000 }).catch(() => {}); throw error;
} finally { await browser.close(); }
